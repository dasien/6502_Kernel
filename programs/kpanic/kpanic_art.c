/* ============================================================================
 * kpanic_art.c -- KERNEL PANIC's pictures.
 *
 * Bitmap sprites live in the VIC's pattern RAM: 16x16 pixels at 4 bits a pixel,
 * 128 bytes a slot, two pixels a byte with the LEFT one in the high nibble. 0 is
 * transparent and 1-15 are palette slots (default palette: 1 red, 2 green,
 * 4 blue, 6 cyan, 8 grey, 9 bright red, A bright green, B bright yellow,
 * C bright blue, D bright magenta, E bright cyan, F white).
 *
 * Each array carries its picture above it as text, one character a pixel, so the
 * bytes can be checked against the drawing. The art was converted from
 * GameSupply's space asset packs (gamesupply.itch.io), used under their licence.
 *
 * Some slots are not stored here but derived at start-up: the craft's impact
 * flash, each enemy's hit flash, the spent spread shot, and every combination of
 * surviving shots in a spread volley. See art_load() in kpanic.c.
 * ==========================================================================*/
